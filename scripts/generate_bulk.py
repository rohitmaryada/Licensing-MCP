#!/usr/bin/env python3
"""
A2 — deterministic bulk data generator for the deep-hierarchy schema (db/schema.sql).

Design (why it looks the way it does):

  * Deterministic. One seeded RNG drives every draw, so a given (--seed, --scale)
    always produces byte-identical data. That's what lets A3 plant golden records
    reproducibly and lets us diff loads.

  * Streaming COPY, not ORM. At ~10M rows, row-by-row INSERT/ORM is hopeless. We
    stream rows straight into Postgres `COPY ... FROM STDIN` (psycopg3), never
    materializing a table in memory.

  * The generator OWNS the ids. Ids are assigned 1..N per table by construction and
    written explicitly (schema uses GENERATED BY DEFAULT AS IDENTITY). Because we
    know every parent's id range up front, children pick coherent FKs with zero DB
    round-trips. After loading we bump each identity sequence past max(id).

  * Referential COHERENCE via contiguous allocation. Each parent owns a contiguous
    block of child ids (users of an entity, licenses of a master license, ...). So
    "a random user of this entity" is just base+randrange(count) — coherent and
    O(1), no per-row lookup tables for the huge tables.

Proportions emerge from per-parent draws (see BASE below); --scale multiplies the
entity count and everything else follows, keeping ratios stable at any size.

Run (small smoke test):
    LICENSING_PG_URL=postgresql://postgres:x@localhost:5433/lic \
        .venv/bin/python scripts/generate_bulk.py --reset --scale 0.003 --verify

Full ~10M-row load (minutes; point at Neon):
    LICENSING_PG_URL="$NEON_URL" .venv/bin/python scripts/generate_bulk.py --reset --scale 1.0

A3 — plant the demo scenario (Acme Corp / jane.doe / stale activation) on top
of the bulk load. --plant-demo requires --reset in the same invocation: it is
not idempotent (plain INSERTs, no upsert), so running it alone against an
already-populated DB would duplicate the demo rows on every rerun.
    LICENSING_PG_URL=postgresql://licensing:licensing@localhost:5433/licensing \
        .venv/bin/python scripts/generate_bulk.py --reset --plant-demo --verify
"""
