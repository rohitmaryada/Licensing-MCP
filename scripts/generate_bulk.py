def fix_sequences(conn):
    """Explicit-id COPY leaves identity sequences at 1 → bump each past max(id)."""
    tables = ["product", "entity", "app_user", "master_license", "license", "license_product",
              "entitlement", "policy", "entitlement_person", "activation",
              "license_end_user", "master_license_admin"]
    for t in tables:
        conn.execute(
            f"SELECT setval(pg_get_serial_sequence('{t}','id'), "
            f"COALESCE((SELECT max(id) FROM {t}), 1), true)")


